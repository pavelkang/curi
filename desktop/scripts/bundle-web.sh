#!/usr/bin/env bash
# Bundle the Curi Next.js standalone build into this Electron app so a
# packaged build runs Studio offline, with no dev server.
#
# Usage (from anywhere):
#   ~/workspace/curi-desktop/scripts/bundle-web.sh
#   # or: npm run bundle:web   (from ~/workspace/curi-desktop)
#
# Prerequisites: a fresh production build in ~/workspace/curi:
#   cd ~/workspace/curi && npm run build
# (next.config.ts sets output: 'standalone', so the build emits
# .next/standalone with server.js + traced node_modules.)
#
# What it copies into resources/curi-web/ (a build artifact, gitignored,
# regenerated by this script — never committed):
#   .next/standalone/*        -> resources/curi-web/   (server.js, .next/server, node_modules)
#   .next/static              -> resources/curi-web/.next/static   (client JS/CSS; NOT in standalone by default)
#   public                    -> resources/curi-web/public         (NOT in standalone by default)
#
# The packaged Electron main process (src/main.js) spawns
# resources/curi-web/server.js with ELECTRON_RUN_AS_NODE=1 and loads
# http://127.0.0.1:<port>/studio once the port responds.
set -euo pipefail

CURI_WEB="$(cd "$(dirname "$0")/../../curi" && pwd)"
DESKTOP="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$CURI_WEB/.next/standalone"
DEST="$DESKTOP/resources/curi-web"

if [ ! -f "$SRC/server.js" ]; then
  echo "error: $SRC/server.js not found — run 'npm run build' in $CURI_WEB first (output: 'standalone')." >&2
  exit 1
fi
if [ ! -d "$CURI_WEB/.next/static" ]; then
  echo "error: $CURI_WEB/.next/static not found — run 'npm run build' in $CURI_WEB first." >&2
  exit 1
fi

rm -rf "$DEST"
mkdir -p "$DEST"
# cp -r (not -a): this VM cannot preserve ownership on some traced files,
# and -a aborts the copy on those errors. Contents + modes are what matter.
cp -r "$SRC/." "$DEST/"
mkdir -p "$DEST/.next"
cp -r "$CURI_WEB/.next/static" "$DEST/.next/static"
if [ -d "$CURI_WEB/public" ]; then
  cp -r "$CURI_WEB/public" "$DEST/public"
fi

echo "bundled: $SRC -> $DEST"
du -sh "$DEST"
ls "$DEST/server.js" "$DEST/.next/static" >/dev/null && echo "ok: server.js + .next/static present"
