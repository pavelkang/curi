// Server-only Mux helpers. All secrets come from env vars; none are
// hard-coded. These run in Route Handlers, never in the browser bundle.
import { createHmac, timingSafeEqual } from "node:crypto";

export function isMuxConfigured(): boolean {
  return Boolean(process.env.MUX_TOKEN_ID) && Boolean(process.env.MUX_TOKEN_SECRET);
}

function muxAuthHeader(): string {
  const id = process.env.MUX_TOKEN_ID ?? "";
  const secret = process.env.MUX_TOKEN_SECRET ?? "";
  return `Basic ${Buffer.from(`${id}:${secret}`).toString("base64")}`;
}

export async function createMuxDirectUpload(opts: { lessonId?: string }): Promise<{
  uploadUrl: string;
  uploadId: string;
}> {
  if (!isMuxConfigured()) throw new Error("MUX_TOKEN_ID / MUX_TOKEN_SECRET are not configured");
  const res = await fetch("https://api.mux.com/video/v1/uploads", {
    method: "POST",
    headers: {
      Authorization: muxAuthHeader(),
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      cors_origin: "*",
      new_asset_settings: {
        playback_policies: ["public"],
        // Auto captions: Mux generates English subtitles for direct
        // uploads when generated_subtitles is set on the first input.
        // See https://www.mux.com/docs/guides/add-autogenerated-captions-and-use-transcripts
        inputs: [
          {
            generated_subtitles: [{ language_code: "en", name: "English (auto)" }],
          },
        ],
        // Passthrough lets the webhook map the finished asset back to
        // the lesson it came from. It is the lesson id, nothing else.
        ...(opts.lessonId ? { passthrough: opts.lessonId } : {}),
      },
    }),
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`Mux upload creation failed (${res.status}): ${text.slice(0, 500)}`);
  }
  const json = (await res.json()) as { data?: { url?: string; id?: string } };
  if (!json.data?.url || !json.data?.id) throw new Error("Mux returned an upload without url/id");
  return { uploadUrl: json.data.url, uploadId: json.data.id };
}

export async function createMuxTextTrack(opts: {
  assetId: string;
  url: string;
  languageCode?: string;
  name?: string;
}): Promise<unknown> {
  // Mux's create-track API takes a publicly hosted VTT/SRT *URL*.
  // It does not accept raw VTT text. That is why in-app edited VTT
  // text is stored in the lesson block (see lib/content.ts) and the
  // player renders it from a blob URL, rather than this route being
  // presented as "edit captions in Mux". This route is for the case
  // where the creator already has a public VTT URL.
  if (!isMuxConfigured()) throw new Error("MUX_TOKEN_ID / MUX_TOKEN_SECRET are not configured");
  const res = await fetch(`https://api.mux.com/video/v1/assets/${encodeURIComponent(opts.assetId)}/tracks`, {
    method: "POST",
    headers: {
      Authorization: muxAuthHeader(),
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      url: opts.url,
      type: "text",
      text_type: "subtitles",
      language_code: opts.languageCode ?? "en",
      closed_captions: true,
      name: opts.name ?? "English",
    }),
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`Mux track creation failed (${res.status}): ${text.slice(0, 500)}`);
  }
  return res.json();
}

export function verifyMuxWebhookSignature(rawBody: string, signatureHeader: string | null): boolean {
  const secret = process.env.MUX_WEBHOOK_SECRET;
  if (!secret) return true; // No secret configured: caller logs this gap.
  if (!signatureHeader) return false;
  // Mux-Signature: t=<timestamp>,v1=<hmac-sha256 hex of "<timestamp>.<body>">
  const parts = Object.fromEntries(
    signatureHeader.split(",").map((p) => {
      const [k, v] = p.split("=");
      return [k, v];
    }),
  );
  const timestamp = parts["t"];
  const expected = parts["v1"];
  if (!timestamp || !expected) return false;
  const digest = createHmac("sha256", secret).update(`${timestamp}.${rawBody}`).digest("hex");
  try {
    return timingSafeEqual(Buffer.from(digest), Buffer.from(expected));
  } catch {
    return false;
  }
}
